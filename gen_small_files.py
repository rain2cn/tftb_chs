def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')

def main():
    src_c = os.path.join(HERE, '_work', 'en', 'Ep1__ui_credits_english.landb')
    d = open(src_c, 'rb').read()
    cred_text = None
    others = []
    for x in landb.extract(d):
        t = x['text']
        if t.startswith('VIRTUOS'):
            cred_text = t
        else:
            others.append(t)
    assert cred_text is not None, '未找到致谢名单'

    lines = cred_text.split('\n')
    out = []
    replaced = 0
    for ln in lines:
        st = ln.strip()
        if st in CREDITS_LABELS:
            out.append(ln.replace(st, CREDITS_LABELS[st])); replaced += 1
        elif st in KEEP_LABELS or not st:
            out.append(ln)
        else:
            out.append(ln)
    cred_out = '\n'.join(out)
    print('职务标签替换 %d 处' % replaced)

    pairs = [
        ("Death of a Stepsister", "继妹之死"),
        (others[0] if others else '', RHYS_INTRO),
        (others[1] if len(others) > 1 else '', CAM_INTRO),
        (cred_text, cred_out),
        ("Zer0 Sum", "Zer0 Sum"),
    ]
    # others 顺序为：[Death of a Stepsister, RHYS_INTRO_en, CAM_INTRO_en, Zer0 Sum]
    intro_rhys_en = None; intro_cam_en = None
    for t in others:
        if t.startswith('You are RHYS'):
            intro_rhys_en = t
        elif t.startswith('You are CAM'):
            intro_cam_en = t
    assert intro_rhys_en and intro_cam_en, '未找到两段简介'

    with open(os.path.join(HERE, 'tr', 'ui_credits_zh.py'), 'w', encoding='utf-8') as f:
        f.write('# ui_credits_english.landb 译文（致谢名单：仅译职务标签，人名/公司名保留）\n')
        f.write('T = {\n')
        for en, zh in (("Death of a Stepsister", "继妹之死"),
                       (intro_rhys_en, RHYS_INTRO),
                       (intro_cam_en, CAM_INTRO),
                       (cred_text, cred_out),
                       ("Zer0 Sum", "Zer0 Sum")):
            f.write('    "%s":\n        "%s",\n' % (esc(en), esc(zh)))
        f.write('}\n')
    print('已写 tr/ui_credits_zh.py')

if __name__ == '__main__':
    main()
